std::string xml_escape(const std::string& in) {
    std::string out;
    for (const char c : in) {
        switch (c) {
            case '&': out += "&amp;"; break;
            case '<': out += "&lt;"; break;
            case '>': out += "&gt;"; break;
            case '"': out += "&quot;"; break;
            case '\'': out += "&apos;"; break;
            default:
                if (static_cast<unsigned char>(c) < 0x20) throw std::invalid_argument("control character in web.config value");
                out += c;
        }
    }
    return out;
}

void set_var(std::string& out, const std::string& name, const std::string& value, const char* indent) {
    out += indent;
    out += "<set name=\"" + xml_escape(name) + "\" value=\"" + xml_escape(value) + "\" />\n";
}

